import assert from 'node:assert/strict';
import test from 'node:test';
import { Box3, Mesh } from 'three';
import { createWorld } from '../src/world';

test('world renders a sampled volume, switches actual resolution and releases resources', () => {
  const world = createWorld(42);
  assert.equal(world.group.children.length, 1);
  const mesh = world.group.children[0] as Mesh;
  assert.equal(mesh.geometry.type, 'BufferGeometry');
  const high = mesh.geometry;
  const count = high.getAttribute('position').count;
  assert.ok(count > 30000, 'resolved surface geometry');
  const box = new Box3().setFromObject(world.group);
  assert.ok(box.min.toArray().every(Number.isFinite));
  assert.ok(box.max.toArray().every(Number.isFinite));
  assert.ok(box.min.x > -13 && box.max.x < 13);
  assert.ok(box.max.y - box.min.y > 1, 'genuine three-dimensional extent');
  world.update(12, { intensity: 1, speed: 1, quality: 'low' });
  const low = mesh.geometry;
  assert.ok(low.getAttribute('position').count < count);
  world.update(12, { intensity: 1, speed: 1, quality: 'high' });
  assert.equal(mesh.geometry, high);
  let disposedHigh = 0, disposedLow = 0;
  high.addEventListener('dispose', () => disposedHigh++);
  low.addEventListener('dispose', () => disposedLow++);
  world.dispose(); world.dispose();
  assert.equal(disposedHigh, 1); assert.equal(disposedLow, 1);
  assert.equal(world.group.children.length, 0);
});
